library(psilocybinresearch)
x <- annual_counts(data.frame(publication_year = c(2025L, 2025L, 2026L, NA_integer_)))
stopifnot(sum(x$records) == 4L, x$records[is.na(x$year)] == 1L)
stopifnot(inherits(try(annual_counts(data.frame(x=1)), silent=TRUE), "try-error"))
stopifnot(inherits(try(download_snapshot(tempdir(), list()), silent=TRUE), "try-error"))
d <- tempfile(); dir.create(d)
papers <- data.frame(id=1:2, publication_year=c(2025L,NA_integer_), publication_status=c('published','preprint'))
saveRDS(list(publications=papers), file.path(d,'publications.rds'))
sha <- digest::digest(file=file.path(d,'publications.rds'),algo='sha256')
m <- list(complete=TRUE,snapshot_id=paste(rep('a',64),collapse=''),record_count=2L,artifacts=list(rds=list(sha256=sha)))
jsonlite::write_json(m,file.path(d,'dataset-manifest.json'),auto_unbox=TRUE)
stopifnot(nrow(read_snapshot(d)$publications)==2L)
cat('corrupted',file=file.path(d,'publications.rds'))
stopifnot(inherits(try(read_snapshot(d),silent=TRUE),'try-error'))
unlink(d,recursive=TRUE)
